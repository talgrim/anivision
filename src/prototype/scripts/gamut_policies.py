"""Compare gamut policies (clip vs desaturate) for V2 on the charts and photos.

For every pixel the matrix sends outside the sRGB gamut, the "target" is the unclipped colour
(its CIELAB value is still defined). Each policy's displayed colour is scored against it:
CIEDE2000, lightness error, hue-angle error (where the target is clearly chromatic) and the
fraction of chroma kept. Writes out/gamut_policies.md and out/gamut_policies.png.

Usage (from src/prototype):  PYTHONPATH=. .venv/bin/python scripts/gamut_policies.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

from anivision.cli import load_rgb
from anivision.colorspace import linear_to_srgb, srgb_to_linear, to_float
from anivision.gamut import GAMUT_POLICIES, fit_to_gamut
from anivision.metrics import chroma, delta_e_2000, linear_rgb_to_lab
from anivision.simulate import GAMUT_TOLERANCE, apply_matrix
from anivision.variants import DOG_V2

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "out"
MAX_EDGE = 900
SHEET_IMAGES = ["charts/blue_yellow", "charts/hue_wheel", "charts/primaries", "photos/orange-buoy", "photos/autumn", "photos/apples"]


def load(path: Path) -> np.ndarray:
    img = load_rgb(str(path))
    h, w = img.shape[:2]
    if max(h, w) > MAX_EDGE:
        s = MAX_EDGE / max(h, w)
        img = np.asarray(Image.fromarray(img).resize((round(w * s), round(h * s)), Image.LANCZOS))
    return img


def hue_diff_deg(lab_a: np.ndarray, lab_b: np.ndarray) -> np.ndarray:
    ha = np.degrees(np.arctan2(lab_a[..., 2], lab_a[..., 1]))
    hb = np.degrees(np.arctan2(lab_b[..., 2], lab_b[..., 1]))
    return np.abs((ha - hb + 180.0) % 360.0 - 180.0)


def score(mapped: np.ndarray, policy: str) -> dict | None:
    bad = ((mapped < -GAMUT_TOLERANCE) | (mapped > 1 + GAMUT_TOLERANCE)).any(axis=-1)
    if not bad.any():
        return None
    target = linear_rgb_to_lab(mapped[bad])
    shown_rgb = fit_to_gamut(mapped, policy)
    shown = linear_rgb_to_lab(shown_rgb[bad])
    chromatic = chroma(target) > 5.0
    return {
        "n": int(bad.sum()),
        "de": delta_e_2000(target, shown),
        "dl": np.abs(target[:, 0] - shown[:, 0]),
        "dh": hue_diff_deg(target, shown)[chromatic] if chromatic.any() else np.array([0.0]),
        "kept": (chroma(shown) / np.maximum(chroma(target), 1e-9)),
    }


def tile(arr: np.ndarray, label: str, w=300, h=225) -> Image.Image:
    im = Image.fromarray(arr)
    im.thumbnail((w, h))
    t = Image.new("RGB", (w, h + 18), (28, 28, 28))
    t.paste(im, ((w - im.width) // 2, 0))
    ImageDraw.Draw(t).text((4, h + 2), label, fill=(230, 230, 230), font=ImageFont.load_default(size=13))
    return t


def main() -> int:
    paths = sorted((ROOT / "samples" / "charts").glob("*.png")) + sorted((ROOT / "samples" / "photos").glob("*.jpg"))
    rows, per = [], {}
    sheet_rows = []
    for path in paths:
        key = f"{path.parent.name}/{path.stem}"
        img = load(path)
        mapped = apply_matrix(srgb_to_linear(to_float(img)), DOG_V2)
        scores = {p: score(mapped, p) for p in GAMUT_POLICIES}
        if scores["clip"] is None:
            continue
        per[key] = scores
        n = scores["clip"]["n"]
        row = [key, f"{n / mapped[..., 0].size:.1%}"]
        for p in GAMUT_POLICIES:
            s = scores[p]
            row += [f"{s['de'].mean():.1f}", f"{s['dl'].mean():.1f}", f"{np.median(s['dh']):.1f}", f"{np.median(s['kept']):.0%}"]
        rows.append(row)
        if key in SHEET_IMAGES:
            shown = [tile(img, key)] + [
                tile(np.asarray(Image.fromarray((linear_to_srgb(fit_to_gamut(mapped, p)) * 255 + 0.5).astype(np.uint8))), f"V2 {p}")
                for p in GAMUT_POLICIES
            ]
            sheet_rows.append(shown)

    head = ["image", "out of gamut"]
    for p in GAMUT_POLICIES:
        head += [f"{p} ΔE", f"{p} ΔL*", f"{p} Δhue°", f"{p} chroma kept"]
    lines = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]

    # Pooled over every out-of-gamut pixel in the test set.
    pooled = ["", "Pooled over all out-of-gamut pixels in the test set (means; hue is a median):", "",
              "| policy | pixels | mean ΔE00 | mean ΔL* | median Δhue (deg) | median chroma kept |", "|---|---|---|---|---|---|"]
    for p in GAMUT_POLICIES:
        cat = {k: np.concatenate([per[i][p][k] for i in per]) for k in ("de", "dl", "dh", "kept")}
        pooled.append(f"| {p} | {sum(per[i][p]['n'] for i in per)} | {cat['de'].mean():.2f} | {cat['dl'].mean():.2f} | {np.median(cat['dh']):.1f} | {np.median(cat['kept']):.0%} |")

    text = (
        "# Gamut policies for V2 (generated by scripts/gamut_policies.py)\n\n"
        "Scores compare the displayed colour with the unclipped colour the matrix asked for, on the\n"
        "out-of-gamut pixels only (ΔE = CIEDE2000, ΔL* = lightness error, Δhue = hue-angle error where\n"
        "the target chroma is above 5, chroma kept = shown / target).\n\n" + "\n".join(lines) + "\n" + "\n".join(pooled) + "\n"
    )
    OUT.mkdir(exist_ok=True)
    (OUT / "gamut_policies.md").write_text(text, encoding="utf-8")
    print(text)

    tw, th = 300, 243
    sheet = Image.new("RGB", (tw * 3, th * len(sheet_rows)), (28, 28, 28))
    for r, row in enumerate(sheet_rows):
        for c, t in enumerate(row):
            sheet.paste(t, (c * tw, r * th))
    sheet.save(OUT / "gamut_policies.png")
    print("wrote out/gamut_policies.png")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
